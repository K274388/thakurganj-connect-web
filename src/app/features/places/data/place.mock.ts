import { PLACE_CATEGORIES } from './place-category.mock';
import { Place } from '../models/place.models';

type PlaceSeed = Pick<Place, 'id' | 'slug' | 'name' | 'categorySlug' | 'shortDescription'> &
  Partial<
    Pick<Place, 'area' | 'landmark' | 'description' | 'address' | 'featured' | 'active' | 'displayOrder'>
  >;

function createPlace(seed: PlaceSeed): Place {
  const category = PLACE_CATEGORIES.find((item) => item.slug === seed.categorySlug);
  if (!category) throw new Error(`Unknown place category: ${seed.categorySlug}`);

  return {
    ...seed,
    categoryId: category.id,
    categorySlug: category.slug,
    categoryName: category.name,
    description: seed.description ?? seed.shortDescription,
    address: seed.address ?? (seed.area ? `${seed.area}, Thakurganj` : 'Thakurganj'),
    area: seed.area ?? 'Thakurganj',
    landmark: seed.landmark ?? '',
    pinCode: '',
    latitude: null,
    longitude: null,
    coverImageUrl: null,
    images: [],
    featured: seed.featured ?? false,
    active: seed.active ?? true,
    displayOrder: seed.displayOrder ?? 0,
  };
}

